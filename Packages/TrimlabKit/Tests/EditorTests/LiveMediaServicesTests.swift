import AVFoundation
import Foundation
import Testing
import TrimlabMedia
import TrimlabModel
@testable import TrimlabEditor

/// `LiveMediaServices` on the real cache and real fixtures.
@Suite(.serialized) struct LiveMediaServicesTests {
  /// A cache root with `names` as entry directories of 500 bytes each, the first the oldest.
  static func fillCache(_ root: URL, _ names: [String]) throws {
    let fm = FileManager.default
    for (i, name) in names.enumerated() {
      let dir = root.appending(path: name, directoryHint: .isDirectory)
      try fm.createDirectory(at: dir, withIntermediateDirectories: true)
      try Data(count: 500).write(to: dir.appending(path: "poster.jpg"))
      let t = Date(timeIntervalSinceNow: Double(i - 10) * 100)
      try fm.setAttributes([.modificationDate: t], ofItemAtPath: dir.path)
      var tv = [timeval(tv_sec: Int(t.timeIntervalSince1970), tv_usec: 0),
                timeval(tv_sec: Int(t.timeIntervalSince1970), tv_usec: 0)]
      utimes(dir.path, &tv)
    }
  }

  /// I-1: launch prunes the cache (LRU, to its limit), not only opening a project.
  @Test func warmUpPrunesTheCache() async throws {
    let root = FileManager.default.temporaryDirectory.appending(path: "trimlab2-warm-\(UUID())", directoryHint: .isDirectory)
    try FileManager.default.createDirectory(at: root, withIntermediateDirectories: true)
    defer { try? FileManager.default.removeItem(at: root) }
    try Self.fillCache(root, ["k1", "k2", "k3"])
    let media = LiveMediaServices(cache: MediaCache(root: root, limitBytes: 1100), logTail: nil)
    await media.warmUp(sweeping: [])
    let fm = FileManager.default
    #expect(!fm.fileExists(atPath: root.appending(path: "k1").path), "the least recently used entry stayed")
    #expect(fm.fileExists(atPath: root.appending(path: "k2").path))
    #expect(fm.fileExists(atPath: root.appending(path: "k3").path))
  }

  // MARK: export on real fixtures (I-3, M-3, M-4)

  /// Packages/TrimlabKit/Tests/Fixtures (generated by the MediaTests fixtures script).
  static let fixtures: URL = {
    var url = URL(filePath: #filePath)
    url.deleteLastPathComponent()
    url.deleteLastPathComponent()
    return url.appending(path: "Fixtures", directoryHint: .isDirectory)
  }()

  /// A scratch folder, removed (and unlocked) afterwards.
  final class Scratch: Sendable {
    let dir: URL
    init() throws {
      dir = FileManager.default.temporaryDirectory.appending(path: "trimlab2-live-\(UUID())", directoryHint: .isDirectory)
      try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
    }
    func url(_ name: String) -> URL { dir.appending(path: name) }
    var names: Set<String> { Set((try? FileManager.default.contentsOfDirectory(atPath: dir.path)) ?? []) }
    func remove() {
      for name in names { try? FileManager.default.setAttributes([.immutable: false], ofItemAtPath: url(name).path) }
      try? FileManager.default.removeItem(at: dir)
    }
  }

  struct Rig {
    let media: LiveMediaServices
    let reel: Reel
    let sources: [UUID: URL]
  }

  /// A Reel of the fixtures `names` (probed with `probing`, whose cache holds any .mkv remux), exported by a media
  /// service with its own, empty cache.
  static func rig(_ names: [String], scratch: Scratch, probing: LiveMediaServices? = nil) async throws -> Rig {
    let prober = probing ?? LiveMediaServices(cache: MediaCache(root: scratch.url("probe-cache")), logTail: nil)
    var clips: [ReelClip] = []
    var sources: [UUID: URL] = [:]
    for name in names {
      let url = fixtures.appending(path: name)
      try #require(FileManager.default.fileExists(atPath: url.path), "fixture \(name) missing")
      let ref = try prober.sourceRef(url, projectFolder: nil)
      let facts = try await prober.probe(url, ref: ref)
      let clip = ReelClip.make(source: ref, facts: facts, framing: .fill)
      clips.append(clip)
      sources[clip.id] = url
    }
    var reel = Reel.empty(name: "live")
    reel.clips = clips
    let media = LiveMediaServices(cache: MediaCache(root: scratch.url("export-cache")), logTail: nil)
    return Rig(media: media, reel: reel, sources: sources)
  }

  /// What a stream ended with.
  struct Outcome {
    var result: ExportResult?
    var error: (any Error)?
  }

  static func drain(_ stream: AsyncThrowingStream<ExportEvent, Error>) async -> Outcome {
    var outcome = Outcome()
    do {
      for try await event in stream { if case .done(let r) = event { outcome.result = r } }
    } catch {
      outcome.error = error
    }
    return outcome
  }

  static func duration(_ url: URL) async throws -> Double {
    try await AVURLAsset(url: url).load(.duration).seconds
  }

  /// I-3: Replace over an existing file: the old file is replaced, no stand-in is left, the result is `dest`.
  @Test func replaceSucceeds() async throws {
    let scratch = try Scratch()
    defer { scratch.remove() }
    let rig = try await Self.rig(["tiny.mp4"], scratch: scratch)
    let dest = scratch.dir.appending(path: "Out.mp4")
    try Data("old".utf8).write(to: dest)
    let done = await Self.drain(rig.media.export(reel: rig.reel, dest: dest, sources: rig.sources, quick: nil,
                                                 replacing: true))
    #expect(done.error == nil, "\(String(describing: done.error))")
    let result = try #require(done.result)
    #expect(result.url == dest)
    let onDisk = (try FileManager.default.attributesOfItem(atPath: dest.path)[.size] as? Int64) ?? 0
    #expect(onDisk == result.bytes && onDisk > 1000, "dest is \(onDisk) bytes")
    #expect(try await Self.duration(dest) > 0.3, "dest isn't the new export")
    #expect(!scratch.names.contains { $0.contains(".replacing.") || $0.contains(".partial.") }, "\(scratch.names)")
  }

  /// I-3: a Replace whose swap fails (the old file is locked): the old file is intact, the new one is kept under a
  /// Keep-both name, and the error says so.
  @Test func replaceThatFailsKeepsTheOriginal() async throws {
    let scratch = try Scratch()
    defer { scratch.remove() }
    let rig = try await Self.rig(["tiny.mp4"], scratch: scratch)
    let dest = scratch.dir.appending(path: "Out.mp4")
    try Data("old".utf8).write(to: dest)
    try FileManager.default.setAttributes([.immutable: true], ofItemAtPath: dest.path)
    let done = await Self.drain(rig.media.export(reel: rig.reel, dest: dest, sources: rig.sources, quick: nil,
                                                 replacing: true))
    let failed = try #require(done.error as? ExportFailed, "\(String(describing: done.error))")
    #expect(failed.error == .notReplaced(name: "Out.mp4", oldKept: true, keptAs: "Out 2.mp4"))
    #expect(done.result == nil)
    #expect(try String(contentsOf: dest, encoding: .utf8) == "old")
    #expect(try await Self.duration(scratch.url("Out 2.mp4")) > 0.3)
    #expect(!scratch.names.contains { $0.contains(".replacing.") || $0.contains(".partial.") }, "\(scratch.names)")
  }

  /// M-4: Replace never replaces a folder: it fails at once, the folder and what is in it are untouched.
  @Test func replaceRefusesAFolder() async throws {
    let scratch = try Scratch()
    defer { scratch.remove() }
    let rig = try await Self.rig(["tiny.mp4"], scratch: scratch)
    let dest = scratch.dir.appending(path: "Out.mp4", directoryHint: .isDirectory)
    try FileManager.default.createDirectory(at: dest, withIntermediateDirectories: true)
    try Data("keep".utf8).write(to: dest.appending(path: "inside.txt"))
    let done = await Self.drain(rig.media.export(reel: rig.reel, dest: dest, sources: rig.sources, quick: nil,
                                                 replacing: true))
    let failed = try #require(done.error as? ExportFailed, "\(String(describing: done.error))")
    #expect(failed.error == .notReplaced(name: "Out.mp4", oldKept: true, keptAs: nil))
    #expect(try String(contentsOf: dest.appending(path: "inside.txt"), encoding: .utf8) == "keep")
    #expect(scratch.names.filter { !$0.hasSuffix("-cache") } == ["Out.mp4"], "\(scratch.names)")
  }

  /// I-3: a cancel while the .mkv is still being remuxed (before any runner exists) ends the stream with a cancel,
  /// leaves nothing behind, and (M-3) the media layer is free the moment `cancelExport` returns.
  @Test func cancelBeforeTheRunnerExists() async throws {
    let scratch = try Scratch()
    defer { scratch.remove() }
    try #require(LiveMediaServices(cache: MediaCache(root: scratch.url("x")), logTail: nil).ffmpegAvailable(),
                 "ffmpeg is needed for the .mkv fixture")
    let rig = try await Self.rig(["sample.mkv"], scratch: scratch)
    let dest = scratch.dir.appending(path: "Out.mp4")
    let stream = rig.media.export(reel: rig.reel, dest: dest, sources: rig.sources, quick: nil, replacing: false)
    let reading = Task { await Self.drain(stream) }
    let stopped = await rig.media.cancelExport()
    #expect(stopped, "the cancel reported nothing stopped")
    // The media layer is free now: a new export starts at once, never "already running".
    let again = rig.media.export(reel: rig.reel, dest: dest, sources: rig.sources, quick: nil, replacing: false)
    let first = await reading.value
    #expect(first.error is CancellationError, "\(String(describing: first.error))")
    #expect(first.result == nil)
    let second = await Self.drain(again)
    #expect(second.error == nil, "\(String(describing: second.error))")
    #expect(second.result?.url == dest)
    #expect(try await Self.duration(dest) > 0.3)
    #expect(!scratch.names.contains { $0.contains(".partial.") || $0.contains(".replacing.") }, "\(scratch.names)")
  }

  /// I-3: a second export while one is running fails with "already running" and corrupts nothing: the first one
  /// completes, and the second's destination is never written.
  @Test func secondExportWhileRunning() async throws {
    let scratch = try Scratch()
    defer { scratch.remove() }
    let rig = try await Self.rig(["landscape.mp4"], scratch: scratch)
    let dest1 = scratch.dir.appending(path: "One.mp4")
    let dest2 = scratch.dir.appending(path: "Two.mp4")
    let first = rig.media.export(reel: rig.reel, dest: dest1, sources: rig.sources, quick: nil, replacing: false)
    let second = rig.media.export(reel: rig.reel, dest: dest2, sources: rig.sources, quick: nil, replacing: false)
    let refused = await Self.drain(second)
    let failed = try #require(refused.error as? ExportFailed, "\(String(describing: refused.error))")
    #expect(failed.error == .other("An export is already running."))
    let done = await Self.drain(first)
    #expect(done.error == nil, "\(String(describing: done.error))")
    #expect(done.result?.url == dest1)
    #expect(try await Self.duration(dest1) > 4)
    #expect(!FileManager.default.fileExists(atPath: dest2.path))
    #expect(!scratch.names.contains { $0.contains(".partial.") || $0.contains(".replacing.") }, "\(scratch.names)")
    // And once it has ended the slot is free again.
    let third = await Self.drain(rig.media.export(reel: rig.reel, dest: dest2, sources: rig.sources, quick: nil,
                                                  replacing: false))
    #expect(third.error == nil, "\(String(describing: third.error))")
  }
}
